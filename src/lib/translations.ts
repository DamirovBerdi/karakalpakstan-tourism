export function getTranslation(lang: Lang, key: string): string {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

export function getText<T = string>(obj: Record<string, unknown> | null | undefined, lang: Lang): T {
  if (!obj) return '' as unknown as T;
  const val = (obj as Record<string, unknown>)[lang] ?? obj['en'] ?? obj['ru'] ?? Object.values(obj)[0];
  return (val ?? '') as unknown as T;
}
